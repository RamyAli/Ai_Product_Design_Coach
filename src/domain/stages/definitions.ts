export const STAGE_DEFINITIONS: readonly StageDefinition[] = [
  discovery,
  research,
  architecture,
  wireframes,
  visualDesign,
  prototype,
  usabilityTesting,
  handoff,
];

const byKey = new Map(STAGE_DEFINITIONS.map((s) => [s.key, s]));

export function getStageDefinition(key: StageKey | string): StageDefinition {
  const def = byKey.get(key as StageKey);
  if (!def) throw new Error(`Unknown stage key: ${key}`);
  return def;
}

/** Stages that transitively depend on the given stage (downstream impact). */
export function downstreamStages(key: StageKey): StageKey[] {
  const result = new Set<StageKey>();
  let frontier: StageKey[] = [key];
  while (frontier.length) {
    const next: StageKey[] = [];
    for (const def of STAGE_DEFINITIONS) {
      if (result.has(def.key) || def.key === key) continue;
      if (def.dependsOn.some((d) => frontier.includes(d))) {
        result.add(def.key);
        next.push(def.key);
      }
    }
    frontier = next;
  }
  return STAGE_DEFINITIONS.filter((d) => result.has(d.key)).map((d) => d.key);
}

/** Canonical stage title in the requested UI language. */
export function stageTitle(stageKey: string, locale: "en" | "ar"): string {
  const def = byKey.get(stageKey as StageKey);
  if (!def) return stageKey;
  return typeof def.title === "string" ? def.title : def.title[locale];
}
